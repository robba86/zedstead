# Archive name for the app config file inside full backups
APP_CONFIG_ARC_NAME = "_zsm/config.json"
# The mod list lives beside config.json, outside the server dir, and goes
# back with the server files (plans/77).
MODS_ARC_NAME = "_zsm/mods.json"

# Directories always excluded from full backups.
#
# `.zsm-mod-rollback` holds the mod versions the last update replaced (TODO
# C5). It is by definition a *second* copy of mods this backup either already
# contains or was told to leave out, so including it would silently double the
# size of a full backup with `include_mods` — and restoring it would put a
# stale rollback offer back on a server that has moved on.
_ALWAYS_EXCLUDE_DIRS = {
    ".venv",
    "__pycache__",
    ".git",
    ".mypy_cache",
    "node_modules",
    ".zsm-mod-rollback",
}

# Log file extensions excluded by default
_LOG_EXTENSIONS = {".log", ".rpt", ".mdmp", ".adm"}


@dataclass
class FullBackupOptions:
    include_mods: bool = False
    include_logs: bool = False
    note: str = ""


@dataclass
class FullBackupMetadata:
    timestamp: str
    server_dir: str
    include_mods: bool
    include_logs: bool
    file_count: int
    total_size: int
    compressed_size: int
    note: str = ""
    includes_app_config: bool = False


@dataclass
class FullBackupInfo:
    zip_path: Path
    meta_path: Path
    metadata: FullBackupMetadata


# ── Collect files ────────────────────────────────────────────────────


def collect_full_backup_files(
    server_dir: Path, options: FullBackupOptions
) -> dict[str, Path]:
    """Walk server_dir gathering files for a full backup.

    Uses os.walk() for efficient directory pruning.
    Returns dict of {archive_name: full_path}.
    """
    files: dict[str, Path] = {}
    server_dir_str = str(server_dir)

    for dirpath, dirnames, filenames in os.walk(server_dir):
        # Prune always-excluded directories in-place
        dirnames[:] = [
            d for d in dirnames
            if d not in _ALWAYS_EXCLUDE_DIRS
            and not (not options.include_mods and d.startswith("@"))
        ]

        rel_dir = os.path.relpath(dirpath, server_dir_str)

        for fname in filenames:
            # Skip cache files
            if fname in _CACHE_FILES:
                continue

            # Skip log files unless opted in
            if not options.include_logs:
                _, ext = os.path.splitext(fname)
                if ext.lower() in _LOG_EXTENSIONS:
                    continue

            full_path = Path(dirpath) / fname
            if rel_dir == ".":
                arc_name = fname
            else:
                arc_name = f"{rel_dir}/{fname}"
            files[arc_name] = full_path

    return files


# ── Create full backup ───────────────────────────────────────────────


def create_full_backup(
    config: DayzConfig,
    options: FullBackupOptions,
    log: Callable[[str], None] | None = None,
) -> Path | None:
    """Create a full server directory backup. Returns zip path or None."""
    server_dir = config.server_dir_path
    if not server_dir.is_dir():
        if log:
            log("Server directory not found.")
        return None

    if log:
        log("Collecting files...")

    files = collect_full_backup_files(server_dir, options)
    if not files:
        if log:
            log("No files to backup.")
        return None

    # Include this instance's app config file (outside server dir)
    app_config = config.paths.config_file
    includes_app_config = app_config.is_file()
    if includes_app_config:
        files[APP_CONFIG_ARC_NAME] = app_config
    if config.paths.mods_json.is_file():
        files[MODS_ARC_NAME] = config.paths.mods_json

    backup_dir = get_backup_dir(config)
    backup_dir.mkdir(parents=True, exist_ok=True)

    now = datetime.now().astimezone()
    timestamp = now.strftime("%Y%m%d-%H%M%S")
    zip_path, meta_path = _free_backup_paths(backup_dir, f"dayz-server-backup-{timestamp}")

    total_size = sum(f.stat().st_size for f in files.values())
    total_files = len(files)

    if log:
        log(f"Backing up {total_files} files ({_format_size(total_size)})")
        if options.include_mods:
            log("  Including mod directories")
        else:
            log("  Excluding mod directories (re-downloadable)")

    try:
        # Owner-only: it carries config.json and the server's passwords.
        with private_zip(zip_path, compression=zipfile.ZIP_DEFLATED, compresslevel=1) as zf:
            for i, (arc_name, full_path) in enumerate(sorted(files.items()), 1):
                zf.write(full_path, arc_name)
                if log and (i % 100 == 0 or i == total_files):
                    log(f"  [{i}/{total_files}] {arc_name}")
    except Exception:
        # Clean up partial zip on failure
        if zip_path.exists():
            zip_path.unlink()
        raise

    compressed_size = zip_path.stat().st_size

    metadata = FullBackupMetadata(
        timestamp=now.isoformat(),
        server_dir=str(server_dir),
        include_mods=options.include_mods,
        include_logs=options.include_logs,
        file_count=total_files,
        total_size=total_size,
        compressed_size=compressed_size,
        note=options.note,
        includes_app_config=includes_app_config,
    )
    atomic_write_text(meta_path, json.dumps(asdict(metadata), indent=2) + "\n")

    if log:
        log(f"  Compressed: {_format_size(compressed_size)}")

    # Rotate old full backups
    rotate_full_backups(config, log=log)

    return zip_path


# ── List full backups ────────────────────────────────────────────────


def list_full_backups(config: DayzConfig) -> list[FullBackupInfo]:
    """List full server backups, newest-first."""
    backup_dir = get_backup_dir(config)
    if not backup_dir.is_dir():
        return []

    results: list[FullBackupInfo] = []
    for meta_path in sorted(backup_dir.glob("dayz-server-backup-*.meta.json"), reverse=True):
        zip_name = meta_path.name.replace(".meta.json", ".zip")
        zip_path = backup_dir / zip_name
        if not zip_path.is_file():
            continue

        meta_data = _read_sidecar(meta_path)
        if meta_data is None:
            continue
        try:
            metadata = FullBackupMetadata(
                timestamp=meta_data["timestamp"],
                server_dir=meta_data["server_dir"],
                include_mods=meta_data.get("include_mods", False),
                include_logs=meta_data.get("include_logs", False),
                file_count=meta_data.get("file_count", 0),
                total_size=meta_data.get("total_size", 0),
                compressed_size=meta_data.get("compressed_size", 0),
                note=meta_data.get("note", ""),
                includes_app_config=meta_data.get("includes_app_config", False),
            )
        except KeyError:
            continue

        results.append(FullBackupInfo(
            zip_path=zip_path,
            meta_path=meta_path,
            metadata=metadata,
        ))

    # By the sidecar's timestamp, as `list_backups`: a same-second ``-2``
    # sorts before its first by name, and rotation would delete the newer.
    results.sort(key=lambda b: b.metadata.timestamp, reverse=True)
    return results


# ── Restore full backup ─────────────────────────────────────────────


def restore_full_backup(
    config: DayzConfig,
    backup: FullBackupInfo,
    log: Callable[[str], None] | None = None,
) -> int:
    """Extract full backup to server_dir. Returns file count."""
    server_dir = config.server_dir_path
    if not server_dir.is_dir():
        if log:
            log("Server directory not found.")
        return 0

    if log:
        log(f"Restoring from: {backup.zip_path.name}")
        log(f"  To: {server_dir}")

    count = 0
    with zipfile.ZipFile(backup.zip_path, "r") as zf:
        total = sum(
            1 for e in zf.infolist()
            if not e.is_dir() and not e.filename.startswith("_zsm/")
        )
        for entry in zf.infolist():
            if entry.is_dir():
                continue
            # Skip app config entries (restored separately via panel)
            if entry.filename.startswith("_zsm/"):
                continue

            # One entry that would land outside server_dir is skipped and
            # named, like the quick restore and the bundle import, rather than
            # ending the restore half way through (plans/68 B11).
            try:
                target = safe_extract_path(server_dir, entry.filename)
            except ValueError:
                if log:
                    log(f"  - {entry.filename} (unsafe path)")
                continue
            target.parent.mkdir(parents=True, exist_ok=True)
            with zf.open(entry) as src, open(target, "wb") as dst:
                dst.write(src.read())
            count += 1
            if log and (count % 100 == 0 or count == total):
                log(f"  [{count}/{total}] {entry.filename}")
        if MODS_ARC_NAME in zf.namelist():
            from app.modmgr import modlist

            try:
                n = modlist.replace_from(config, zf.read(MODS_ARC_NAME), f"the backup's {MODS_ARC_NAME}")
                if log:
                    log(f"Restored the mod list ({n} mod(s)).")
            except modlist.ModListError as e:
                if log:
                    log(f"  - the mod list was not restored: {e}")

    if log:
        log(f"Restored {count} file(s).")
    return count


# ── Rotate full backups ─────────────────────────────────────────────


def rotate_full_backups(config: DayzConfig, *, log=None) -> int:
    """Delete oldest full backups when exceeding backup_max_count, each one
    named in *log*."""
    if config.backup_max_count <= 0:
        return 0

    backups = list_full_backups(config)
    if len(backups) <= config.backup_max_count:
        return 0

    to_delete = backups[config.backup_max_count:]
    count = 0
    for b in to_delete:
        if b.zip_path.is_file():
            b.zip_path.unlink()
        if b.meta_path.is_file():
            b.meta_path.unlink()
        count += 1
    _say_rotated(log, to_delete, config.backup_max_count)
    return count


# ── Display helpers ──────────────────────────────────────────────────


def format_full_backup_label(backup: FullBackupInfo) -> str:
    """Format a full backup for display in selection lists."""
    meta = backup.metadata
    try:
        dt = datetime.fromisoformat(meta.timestamp)
        date_str = dt.strftime("%Y-%m-%d %H:%M")
    except (ValueError, TypeError):
        date_str = meta.timestamp[:16]

    size_str = _format_size(meta.compressed_size)
    flags = []
    if meta.include_mods:
        flags.append("mods")
    label = f"{date_str}  {meta.file_count} files  {size_str}"
    if flags:
        label += f"  [{'+'.join(flags)}]"
    if meta.note:
        label += f"  ({meta.note})"
    return label


def extract_app_config(zip_path: Path, config_file: Path) -> None:
    """Extract app config from a full backup zip to *config_file* — the
    restoring instance's own (``config.paths.config_file``).

    Atomic and 0600, as ``DayzConfig.save`` writes it: the file holds the
    credentials, and a crash mid-write must not leave it truncated."""
    import zipfile

    from app.shared.json_utils import atomic_write_bytes

    config_file.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(zip_path, "r") as zf:
        if APP_CONFIG_ARC_NAME in zf.namelist():
            data = zf.read(APP_CONFIG_ARC_NAME)
            atomic_write_bytes(config_file, data, owner_only=True)


def read_app_config(zip_path: Path) -> dict | None:
    """The backup's config.json as a dict, without writing anything.

    Used by the web restore when the current config's path lock is on: it
    applies the backup through ``mutate_config`` keeping the locked fields,
    instead of the wholesale ``extract_app_config`` write that would overwrite
    them (plans/58 A6). Returns None when the zip carries no app config or it
    cannot be read or parsed.
    """
    import json
    import zipfile

    try:
        with zipfile.ZipFile(zip_path, "r") as zf:
            if APP_CONFIG_ARC_NAME not in zf.namelist():
                return None
            data = json.loads(zf.read(APP_CONFIG_ARC_NAME))
    except (OSError, zipfile.BadZipFile, ValueError):  # JSON or its encoding
        return None
    return data if isinstance(data, dict) else None
