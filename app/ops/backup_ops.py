"""Shared business logic for backup & restore operations.

Used by both app/commands/backup.py (Click CLI) and
app/web/routers/backups.py (web UI).
"""

from __future__ import annotations

import json
import os
import zipfile
from dataclasses import dataclass, field, asdict
from datetime import datetime
from pathlib import Path
from typing import Callable

from app.ops.cleanup_ops import StorageInfo, find_storage, storage_dir, storage_name
from app.shared.config import DayzConfig
from app.shared.json_utils import atomic_write_text
from app.shared.zip_utils import private_zip, safe_extract_path


# Files to always skip (regenerated by the server automatically)
_CACHE_FILES = {"types.bin", "events.bin", "globals.bin"}

# Mapping from selection category to paths inside the storage folder
_PLAYERS_FILES = {"players.db"}
_VEHICLES_FILES = {"data/vehicles.bin"}
# Every engine file in data/ but vehicles.bin (its own part): doors, buildings,
# zombies and animals too. With dynamic_*.bin alone, the pre-wipe backup could
# not undo a wipe of door and building state (browser test 2026-11-17, Q2).
_WORLD_GLOBS = {"data/*.bin", "spawnpoints.bin"}

# Mod data: what mods persist beside the engine's own files. Inside the storage
# folder that is every subdirectory the engine does not own (Expansion's `expansion/`,
# CF's `communityframework/`); `data/` is the engine's, and so is `backup/`,
# its own rotation of the hive. Outside it, only the TraderPlus databases —
# player money, stored vehicles and trader stock: TraderPlus' config is not
# persistence.
_ENGINE_DIRS = {"data", "backup"}
_PROFILES_PREFIX = "profiles/"
_MOD_PROFILE_DIRS = (
    "TraderPlus/TraderPlusBankDatabase",
    "TraderPlus/TraderPlusGarageDatabase",
    "TraderPlus/TraderPlusDatabase",
)


# ── Dataclasses ──────────────────────────────────────────────────────


@dataclass
class BackupContents:
    players: bool = True
    vehicles: bool = True
    world: bool = True
    mod_data: bool = True


@dataclass
class BackupMetadata:
    timestamp: str
    mission: str
    map_name: str
    contents: dict[str, bool]
    file_sizes: dict[str, int]
    total_size: int
    note: str = ""


@dataclass
class BackupInfo:
    zip_path: Path
    meta_path: Path
    metadata: BackupMetadata


# ── Helpers ──────────────────────────────────────────────────────────


def get_backup_dir(config: DayzConfig) -> Path:
    """Return the backup directory (config override or default)."""
    if config.backup_dir:
        return Path(config.backup_dir)
    return config.paths.backups_dir


def get_mission_map_name(mission: str) -> str:
    """Lookup human-readable map name from seed_data, or return mission name."""
    from app.maps.registry import terrain_from_mission
    from app.shared.seed_data import VANILLA_MAPS, WORKSHOP_MAPS

    for name, data in VANILLA_MAPS.items():
        if data["mission"] == mission:
            return name
        # An announced map before a zsm release names its mission: by terrain.
        if data.get("terrain") and terrain_from_mission(mission) == data["terrain"]:
            return name
    for name, data in WORKSHOP_MAPS.items():
        template = data.get("mission", {}).get("template", "")
        if template == mission:
            return name
    return mission


def _format_size(size_bytes: int) -> str:
    """Format byte size to human-readable string."""
    if size_bytes >= 1024 * 1024:
        return f"{size_bytes / 1024 / 1024:.1f} MB"
    if size_bytes >= 1024:
        return f"{size_bytes / 1024:.1f} KB"
    return f"{size_bytes} B"


def profiles_dir(config: DayzConfig) -> Path:
    return config.server_dir_path / config.profiles_path


def backup_part(name: str) -> str | None:
    """Which part of a quick backup an archive entry belongs to, or None for
    an entry zsm would never have written there.

    Old backups hold only players, vehicles and world entries, so they classify
    exactly as they did before mod data existed.
    """
    if name in _PLAYERS_FILES:
        return "players"
    if name in _VEHICLES_FILES:
        return "vehicles"
    if name.startswith(_PROFILES_PREFIX):
        rel = name[len(_PROFILES_PREFIX):]
        if any(rel.startswith(d + "/") for d in _MOD_PROFILE_DIRS):
            return "mod_data"
        return None
    head, sep, _ = name.partition("/")
    if sep and head not in _ENGINE_DIRS:
        return "mod_data"
    return "world"


def _files_under(root: Path, base: Path, prefix: str = "") -> dict[str, Path]:
    found: dict[str, Path] = {}
    for p in sorted(root.rglob("*")):
        if p.is_file() and p.suffix != ".lock":
            found[prefix + p.relative_to(base).as_posix()] = p
    return found


# ── Collect files ────────────────────────────────────────────────────


def collect_backup_files(
    storage_path: Path, contents: BackupContents, profiles: Path | None = None
) -> dict[str, Path]:
    """Gather files from the storage folder (and, for mod data, the profiles
    dir) based on selection.

    Returns dict of {archive_name: full_path}, excluding cache files. Profiles
    entries are archived under ``profiles/``.
    """
    files: dict[str, Path] = {}

    if contents.players:
        for name in _PLAYERS_FILES:
            p = storage_path / name
            if p.is_file():
                files[name] = p

    if contents.vehicles:
        for name in _VEHICLES_FILES:
            p = storage_path / name
            if p.is_file():
                files[name] = p

    if contents.world:
        for pattern in _WORLD_GLOBS:
            parent = storage_path
            if "/" in pattern:
                parts = pattern.rsplit("/", 1)
                parent = storage_path / parts[0]
                pattern = parts[1]
            if parent.is_dir():
                for p in parent.glob(pattern):
                    rel = p.relative_to(storage_path).as_posix()
                    if p.is_file() and p.name not in _CACHE_FILES and rel not in _VEHICLES_FILES:
                        files[rel] = p

    if contents.mod_data:
        for sub in sorted(storage_path.iterdir()) if storage_path.is_dir() else []:
            if sub.is_dir() and sub.name not in _ENGINE_DIRS:
                files.update(_files_under(sub, storage_path))
        if profiles is not None:
            for rel in _MOD_PROFILE_DIRS:
                if (profiles / rel).is_dir():
                    files.update(_files_under(profiles / rel, profiles, _PROFILES_PREFIX))

    return files


# ── List backups ─────────────────────────────────────────────────────


def _read_sidecar(meta_path: Path) -> dict | None:
    """A backup's ``.meta.json`` as a dict with a text timestamp, or None.

    One sidecar that is not UTF-8, not an object or has no text timestamp
    raised out of the listing (the sort and the labels need the text), which
    hid every other backup and failed each later backup at its rotation."""
    try:
        data = json.loads(meta_path.read_text(encoding="utf-8"))
    except (OSError, ValueError):  # JSON or its encoding
        return None
    if not isinstance(data, dict) or not isinstance(data.get("timestamp"), str):
        return None
    return data


def list_backups(config: DayzConfig, mission: str | None = None) -> list[BackupInfo]:
    """List available backups, newest-first. Optionally filter by mission."""
    backup_dir = get_backup_dir(config)
    if not backup_dir.is_dir():
        return []

    results: list[BackupInfo] = []
    for meta_path in sorted(backup_dir.glob("dayz-backup-*.meta.json"), reverse=True):
        zip_name = meta_path.name.replace(".meta.json", ".zip")
        zip_path = backup_dir / zip_name
        if not zip_path.is_file():
            continue  # orphaned meta

        meta_data = _read_sidecar(meta_path)
        if meta_data is None:
            continue  # skip malformed
        try:
            metadata = BackupMetadata(
                timestamp=meta_data["timestamp"],
                mission=meta_data["mission"],
                map_name=meta_data["map_name"],
                contents=meta_data["contents"],
                file_sizes=meta_data.get("file_sizes", {}),
                total_size=meta_data.get("total_size", 0),
                note=meta_data.get("note", ""),
            )
        except KeyError:
            continue  # skip malformed

        if mission and metadata.mission != mission:
            continue

        results.append(BackupInfo(
            zip_path=zip_path,
            meta_path=meta_path,
            metadata=metadata,
        ))

    # Sort globally newest-first by the ISO timestamp. The filename embeds a
    # variable-length mission name *before* the timestamp, so the glob order is
    # mission-then-time — not newest-first across missions, which would hide a
    # fresh backup behind an alphabetically-earlier mission in "recent" views.
    results.sort(key=lambda b: b.metadata.timestamp, reverse=True)
    return results


# ── Create backup ────────────────────────────────────────────────────


def _free_backup_paths(backup_dir: Path, base_name: str) -> tuple[Path, Path]:
    """``(zip, meta.json)`` paths for *base_name* that no backup uses yet.

    The name carries the time to the second, so a second backup in the same
    second overwrote the first. A clash gets ``-2``, ``-3`` and on; the
    listings glob the prefix and sort by the sidecar's timestamp, so the
    suffix changes neither."""
    name = base_name
    n = 1
    while (backup_dir / f"{name}.zip").exists() or (backup_dir / f"{name}.meta.json").exists():
        n += 1
        name = f"{base_name}-{n}"
    return backup_dir / f"{name}.zip", backup_dir / f"{name}.meta.json"


def quick_backup_problem(config: DayzConfig) -> str | None:
    """Why a quick backup has nothing to save yet, or None when it can run.

    The persistence folder appears the first time the server runs the
    mission, so on a fresh install the Create button only said "No storage_1
    found" (user test in 2026 Q4). The page disables Create with this
    sentence, and the route refuses with it."""
    if find_storage(config):
        return None
    return (
        f"Nothing to back up yet: the mission has no {storage_name(config)} folder until "
        "the server has run it once. Start the server once, then take a quick backup."
    )


def create_backup(
    config: DayzConfig,
    contents: BackupContents,
    note: str = "",
    log: Callable[[str], None] | None = None,
) -> Path | None:
    """Create a backup zip + meta sidecar. Returns zip path or None if no files."""
    info = find_storage(config)
    if not info:
        if log:
            log(f"No {storage_name(config)} found for current mission.")
        return None

    storage_path = info.path
    mission = info.mission
    map_name = get_mission_map_name(mission)

    files = collect_backup_files(storage_path, contents, profiles_dir(config))
    if not files:
        if log:
            log("No files to backup.")
        return None

    backup_dir = get_backup_dir(config)
    backup_dir.mkdir(parents=True, exist_ok=True)

    now = datetime.now().astimezone()
    timestamp = now.strftime("%Y%m%d-%H%M%S")
    zip_path, meta_path = _free_backup_paths(backup_dir, f"dayz-backup-{mission}-{timestamp}")

    # Build file sizes dict
    file_sizes: dict[str, int] = {}
    total_size = 0
    for arc_name, full_path in files.items():
        size = full_path.stat().st_size
        file_sizes[arc_name] = size
        total_size += size

    if log:
        log(f"Creating backup: {zip_path.name}")
        log(f"  Mission: {mission} ({map_name})")
        log(f"  Files: {len(files)}, Size: {_format_size(total_size)}")

    # Write zip (ZIP_STORED for speed), owner-only: player characters and
    # mod databases (TraderPlus banking) are in it (plans/68 SEC-9).
    with private_zip(zip_path, compression=zipfile.ZIP_STORED) as zf:
        for arc_name, full_path in sorted(files.items()):
            zf.write(full_path, arc_name)
            if log:
                log(f"  + {arc_name} ({_format_size(file_sizes[arc_name])})")

    # Write metadata sidecar
    metadata = BackupMetadata(
        timestamp=now.isoformat(),
        mission=mission,
        map_name=map_name,
        contents={
            "players": contents.players,
            "vehicles": contents.vehicles,
            "world": contents.world,
            "mod_data": contents.mod_data,
        },
        file_sizes=file_sizes,
        total_size=total_size,
        note=note,
    )
    atomic_write_text(meta_path, json.dumps(asdict(metadata), indent=2) + "\n")

    # Rotate old backups
    rotate_backups(config, mission, log=log)

    return zip_path


# ── Rotate backups ───────────────────────────────────────────────────


def _say_rotated(log, deleted: list, limit: int) -> None:
    """One line per backup rotation deleted, in the job's log. It deleted the
    "pre-wipe auto-backup" without a word."""
    if not log:
        return
    for b in deleted:
        note = f" ({b.metadata.note})" if getattr(b.metadata, "note", "") else ""
        log(f"Removed {b.zip_path.stem}{note}: older than the newest {limit} (backup_max_count)")


def rotate_backups(config: DayzConfig, mission: str, *, log=None) -> int:
    """Delete oldest backups when exceeding backup_max_count per mission.

    Returns count of deleted backups. 0 = unlimited. Each one is named in *log*.
    """
    if config.backup_max_count <= 0:
        return 0

    backups = list_backups(config, mission=mission)
    if len(backups) <= config.backup_max_count:
        return 0

    to_delete = backups[config.backup_max_count:]
    delete_backups(to_delete)
    _say_rotated(log, to_delete, config.backup_max_count)
    return len(to_delete)


# ── Restore backup ──────────────────────────────────────────────────


def _restore_target(name: str, storage_path: Path, profiles: Path) -> Path:
    """Where an entry goes back to. Raises ValueError for a path that would
    leave its destination — for a profiles entry, the mod's own database dir,
    so a crafted name cannot reach TraderPlus' config beside it."""
    if not name.startswith(_PROFILES_PREFIX):
        return safe_extract_path(storage_path, name)
    rel = name[len(_PROFILES_PREFIX):]
    for d in _MOD_PROFILE_DIRS:
        if rel.startswith(d + "/"):
            return safe_extract_path(profiles / d, rel[len(d) + 1:])
    raise ValueError(f"not a mod data path: {name!r}")


def restore_backup(
    config: DayzConfig,
    backup: BackupInfo,
    contents: BackupContents,
    log: Callable[[str], None] | None = None,
) -> int:
    """Extract selected parts from backup to the storage folder (mod data
    under ``profiles/`` to the profiles dir). Returns file count.

    An entry that would land outside its destination, or that no part of a
    quick backup can hold, is skipped and logged, never written.
    """
    info = find_storage(config)
    if not info:
        # Create the storage folder if it doesn't exist
        from app.modmgr.mods import get_current_mission
        mission = get_current_mission(config.server_cfg_path)
        if not mission:
            if log:
                log("Cannot determine current mission.")
            return 0
        storage_path = storage_dir(config, mission)
        storage_path.mkdir(parents=True, exist_ok=True)
    else:
        storage_path = info.path

    if log:
        log(f"Restoring from: {backup.zip_path.name}")
        log(f"  To: {storage_path}")

    profiles = profiles_dir(config)
    count = 0
    with zipfile.ZipFile(backup.zip_path, "r") as zf:
        for entry in zf.infolist():
            if entry.is_dir():
                continue

            name = entry.filename
            part = backup_part(name)
            if part is None:
                if log:
                    log(f"  - {name} (not part of a quick backup)")
                continue
            if not getattr(contents, part):
                continue

            try:
                target = _restore_target(name, storage_path, profiles)
            except ValueError:
                if log:
                    log(f"  - {name} (unsafe path)")
                continue
            target.parent.mkdir(parents=True, exist_ok=True)
            with zf.open(entry) as src, open(target, "wb") as dst:
                dst.write(src.read())
            count += 1
            if log:
                log(f"  + {name}")

    if log:
        log(f"Restored {count} file(s).")
    return count


# ── Delete backups ───────────────────────────────────────────────────


def delete_backups(backups: list[BackupInfo]) -> int:
    """Remove zip + meta files for given backups. Returns count deleted."""
    count = 0
    for b in backups:
        if b.zip_path.is_file():
            b.zip_path.unlink()
        if b.meta_path.is_file():
            b.meta_path.unlink()
        count += 1
    return count


# ── Display helpers ──────────────────────────────────────────────────


def format_backup_label(backup: BackupInfo) -> str:
    """Format a backup for display in selection lists."""
    meta = backup.metadata
    try:
        dt = datetime.fromisoformat(meta.timestamp)
        date_str = dt.strftime("%Y-%m-%d %H:%M")
    except (ValueError, TypeError):
        date_str = meta.timestamp[:16]

    parts = []
    if meta.contents.get("players"):
        parts.append("P")
    if meta.contents.get("vehicles"):
        parts.append("V")
    if meta.contents.get("world"):
        parts.append("W")
    if meta.contents.get("mod_data"):
        parts.append("M")
    contents_str = "+".join(parts) if parts else "?"

    size_str = _format_size(meta.total_size)
    label = f"{date_str}  {meta.map_name}  [{contents_str}]  {size_str}"
    if meta.note:
        label += f"  ({meta.note})"
    return label


