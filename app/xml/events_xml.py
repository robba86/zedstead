def _get_text_int(event_elem: ET.Element, tag: str, default: int = 0) -> int:
    """Extract integer text from a child element."""
    elem = event_elem.find(tag)
    if elem is not None and elem.text:
        try:
            return int(elem.text.strip())
        except ValueError:
            pass
    return default


def _attr_int(elem: ET.Element, name: str) -> int:
    """An integer attribute; a missing or bad one reads as 0, on its own."""
    try:
        return int(elem.get(name, "0"))
    except ValueError:
        return 0


def _get_text_str(event_elem: ET.Element, tag: str, default: str = "") -> str:
    """Extract string text from a child element."""
    elem = event_elem.find(tag)
    if elem is not None and elem.text:
        return elem.text.strip()
    return default


def parse_events_file(path: Path, *, preserve_comments: bool = False) -> EventsFile:
    """Parse events.xml, extract EventEntry for each <event> element."""
    tree = load_xml(path, preserve_comments=preserve_comments)
    root = tree.getroot()
    entries: list[EventEntry] = []

    for event_elem in root.findall("event"):
        name = event_elem.get("name", "")

        nominal = _get_text_int(event_elem, "nominal")
        min_val = _get_text_int(event_elem, "min")
        max_val = _get_text_int(event_elem, "max")
        lifetime = _get_text_int(event_elem, "lifetime")
        restock = _get_text_int(event_elem, "restock")
        saferadius = _get_text_int(event_elem, "saferadius")
        distanceradius = _get_text_int(event_elem, "distanceradius")
        cleanupradius = _get_text_int(event_elem, "cleanupradius")
        secondary = _get_text_str(event_elem, "secondary")

        # <flags deletable="0" init_random="0" remove_damaged="1"/>
        flags_elem = event_elem.find("flags")
        flags: dict[str, int] = {}
        if flags_elem is not None:
            for flag_name in EVENT_FLAG_NAMES:
                try:
                    flags[flag_name] = int(flags_elem.get(flag_name, "0"))
                except ValueError:
                    flags[flag_name] = 0
        else:
            flags = {fn: 0 for fn in EVENT_FLAG_NAMES}

        position = _get_text_str(event_elem, "position", "fixed")
        limit = _get_text_str(event_elem, "limit", "mixed")
        active = bool(_get_text_int(event_elem, "active", 1))

        # Parse <children> -> <child .../>
        children: list[EventChild] = []
        children_elem = event_elem.find("children")
        if children_elem is not None:
            for child_elem in children_elem.findall("child"):
                children.append(EventChild(
                    type=child_elem.get("type", ""),
                    **{name: _attr_int(child_elem, name) for name in _CHILD_NUMBERS},
                    element=child_elem,
                ))

        entries.append(EventEntry(
            name=name,
            nominal=nominal,
            min=min_val,
            max=max_val,
            lifetime=lifetime,
            restock=restock,
            saferadius=saferadius,
            distanceradius=distanceradius,
            cleanupradius=cleanupradius,
            secondary=secondary,
            flags=flags,
            position=position,
            limit=limit,
            active=active,
            children=children,
            element=event_elem,
            source_file=path,
        ))

    return EventsFile(path=path, tree=tree, entries=entries)


def save_events_file(ef: EventsFile, *, snapshot: bool = True) -> None:
    """Write modified tree back to disk."""
    save_xml(ef.tree, ef.path, snapshot=snapshot)


