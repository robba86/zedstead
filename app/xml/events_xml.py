# Bohemia's order of an <event>'s children (every stock events.xml): where a
# first one of a kind goes when the element had none. <secondary> sits between
# <cleanupradius> and <flags> wherever a stock event names one.
EVENT_CHILD_ORDER = [
    "nominal", "min", "max", "lifetime", "restock", "saferadius", "distanceradius",
    "cleanupradius", "secondary", "flags", "position", "limit", "active", "children",
]
