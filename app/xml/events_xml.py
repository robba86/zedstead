def _set_child_text(event_elem: ET.Element, tag: str, value: str) -> None:
    """Set the text of a child element, creating it if necessary."""
    elem = event_elem.find(tag)
    if elem is None:
        elem = subelement_in_order(event_elem, tag, EVENT_CHILD_ORDER)
    elem.text = value


def set_event_numeric(entry: EventEntry, field_name: str, value: int) -> None:
    """Update one of the numeric fields (nominal, min, max, etc.) on an event."""
    _set_child_text(entry.element, field_name, str(value))
    setattr(entry, field_name, value)


def set_event_flag(entry: EventEntry, flag_name: str, value: int) -> None:
    """Update a flag attribute on the <flags> element."""
    flags_elem = entry.element.find("flags")
    if flags_elem is None:
        flags_elem = subelement_in_order(entry.element, "flags", EVENT_CHILD_ORDER)
    flags_elem.set(flag_name, str(value))
    entry.flags[flag_name] = value


def set_event_position(entry: EventEntry, value: str) -> None:
    """Update the <position> element."""
    _set_child_text(entry.element, "position", value)
    entry.position = value


def set_event_limit(entry: EventEntry, value: str) -> None:
    """Update the <limit> element."""
    _set_child_text(entry.element, "limit", value)
    entry.limit = value


def set_event_active(entry: EventEntry, active: bool) -> None:
    """Update the <active> element."""
    _set_child_text(entry.element, "active", "1" if active else "0")
    entry.active = active


def set_event_secondary(entry: EventEntry, text: str) -> None:
    """Set the <secondary> element, or remove it for an empty *text*: a stock
    event without a linked one has no <secondary> at all."""
    text = text.strip()
    if text:
        _set_child_text(entry.element, "secondary", text)
    else:
        elem = entry.element.find("secondary")
        if elem is not None:
            entry.element.remove(elem)
    entry.secondary = text


def create_event(
    ef: EventsFile,
    name: str,
    nominal: int = 1,
    min_val: int = 1,
    max_val: int = 1,
    lifetime: int = 1800,
    restock: int = 0,
    saferadius: int = 100,
    distanceradius: int = 500,
    cleanupradius: int = 1000,
) -> EventEntry:
    """Create a new <event> element with sensible defaults and add it to the file."""
    root = ef.tree.getroot()
    event_elem = ET.SubElement(root, "event")
    event_elem.set("name", name)
    event_elem.tail = "\n"

    for tag, val in [
        ("nominal", nominal), ("min", min_val), ("max", max_val),
        ("lifetime", lifetime), ("restock", restock),
        ("saferadius", saferadius), ("distanceradius", distanceradius),
        ("cleanupradius", cleanupradius),
    ]:
        child = ET.SubElement(event_elem, tag)
        child.text = str(val)

    flags_elem = ET.SubElement(event_elem, "flags")
    flags_elem.set("deletable", "1")
    flags_elem.set("init_random", "0")
    flags_elem.set("remove_damaged", "1")

    pos_elem = ET.SubElement(event_elem, "position")
    pos_elem.text = "fixed"
    lim_elem = ET.SubElement(event_elem, "limit")
    lim_elem.text = "mixed"
    act_elem = ET.SubElement(event_elem, "active")
    act_elem.text = "1"
    # No <secondary>: every stock one names an event, and an empty one is a
    # link to nothing. `set_event_secondary` puts it in Bohemia's place.

    entry = EventEntry(
        name=name,
        nominal=nominal,
        min=min_val,
        max=max_val,
        lifetime=lifetime,
        restock=restock,
        saferadius=saferadius,
        distanceradius=distanceradius,
        cleanupradius=cleanupradius,
        secondary="",
        flags={"deletable": 1, "init_random": 0, "remove_damaged": 1},
        position="fixed",
        limit="mixed",
        active=True,
        children=[],
        element=event_elem,
        source_file=ef.path,
    )
    ef.entries.append(entry)
    return entry


def add_event_child(
    entry: EventEntry,
    child_type: str,
    min_val: int,
    max_val: int,
    lootmin: int,
    lootmax: int,
) -> EventChild:
    """Create a new <child> element inside <children> and append to the list."""
    children_elem = entry.element.find("children")
    if children_elem is None:
        children_elem = subelement_in_order(entry.element, "children", EVENT_CHILD_ORDER)
    child_elem = ET.SubElement(children_elem, "child")
    child_elem.set("lootmax", str(lootmax))
    child_elem.set("lootmin", str(lootmin))
    child_elem.set("max", str(max_val))
    child_elem.set("min", str(min_val))
    child_elem.set("type", child_type)
    child = EventChild(
        type=child_type,
        min=min_val,
        max=max_val,
        lootmin=lootmin,
        lootmax=lootmax,
        element=child_elem,
    )
    entry.children.append(child)
    return child


def remove_event(ef: EventsFile, entry: EventEntry) -> None:
    """Remove an <event> and its entry."""
    ef.tree.getroot().remove(entry.element)
    ef.entries.remove(entry)


def rename_event(entry: EventEntry, name: str) -> None:
    """Give an event another name; everything else in it stays."""
    entry.element.set("name", name)
    entry.name = name


def remove_event_child(entry: EventEntry, child: EventChild) -> None:
    """Remove a <child> element from <children>."""
    children_elem = entry.element.find("children")
    if children_elem is not None:
        try:
            children_elem.remove(child.element)
        except ValueError:
            pass
    try:
        entry.children.remove(child)
    except ValueError:
        pass


def set_child_values(
    child: EventChild,
    min_val: int,
    max_val: int,
    lootmin: int,
    lootmax: int,
) -> None:
    """Update min/max/lootmin/lootmax attributes on an existing child.

    Only a value that differs from the one read is written, so a value passed
    back as read keeps the file's own text, even one that read as 0.
    """
    for name, value in zip(_CHILD_NUMBERS, (min_val, max_val, lootmin, lootmax)):
        if value != getattr(child, name):
            child.element.set(name, str(value))
            setattr(child, name, value)


