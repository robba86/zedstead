# ---------------------------------------------------------------------------
# Data structures
# ---------------------------------------------------------------------------

# The number attributes of a <child>, in EventChild's field order.
_CHILD_NUMBERS = ("min", "max", "lootmin", "lootmax")


@dataclass
class EventChild:
    """One <child> element inside <children>."""
    type: str
    min: int
    max: int
    lootmin: int
    lootmax: int
    element: ET.Element = field(default_factory=lambda: ET.Element("child"))


@dataclass
class EventEntry:
    """One <event name="..."> element."""
    name: str
    nominal: int
    min: int
    max: int
    lifetime: int
    restock: int
    saferadius: int
    distanceradius: int
    cleanupradius: int
    secondary: str
    flags: dict[str, int]       # deletable, init_random, remove_damaged
    position: str               # fixed, player, uniform
    limit: str                  # mixed, custom, child, parent
    active: bool
    children: list[EventChild]
    element: ET.Element = field(default_factory=lambda: ET.Element("event"))
    source_file: Path = field(default_factory=Path)


@dataclass
class EventsFile:
    """Parsed events.xml."""
    path: Path
    tree: ET.ElementTree
    entries: list[EventEntry] = field(default_factory=list)


# ---------------------------------------------------------------------------
# Path helpers
# ---------------------------------------------------------------------------

def get_events_path(mission_dir: Path) -> Path | None:
    """Return db/events.xml if it exists."""
    p = mission_dir / "db" / "events.xml"
    return p if p.is_file() else None


def custom_event_names(mission_dir: Path) -> set[str]:
    """Event names defined by the mission's CE-linked `custom/` event files.

    A mod's events fragment is *not* merged into db/events.xml — it is copied to
    `custom/<mod>-events.xml` and registered as `<file type="events"/>` in
    cfgeconomycore.xml, which DayZ loads alongside db/events.xml. So an event can
    be perfectly live on the server and absent from every file db/events.xml
    readers know about; anything that answers "does this event exist?" has to ask
    here too.

    Read-only: these files are regenerated by every merge (see the custom/ rules
    in CLAUDE.md), so nothing may write to them from here.
    """
    from app.xml.xml_economy import registered_custom_entries

    names: set[str] = set()
    for filename, ce_type in registered_custom_entries(mission_dir):
        if ce_type != "events":
            continue
        path = mission_dir / "custom" / filename
        try:
            root = load_xml(path).getroot()
        except Exception:  # unparseable mod XML must not break the caller
            continue
        for elem in root.iter("event"):
            name = elem.get("name")
            if name:
                names.add(name)
    return names


