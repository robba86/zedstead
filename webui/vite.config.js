import { readFileSync, readdirSync } from 'node:fs'
import { join } from 'node:path'
import { defineConfig } from 'vite'
import react from '@vitejs/plugin-react'

// The licence text of every npm package the build puts into app/web/static,
// written beside it as third-party-licenses.txt: MIT, BSD and ISC all ask
// for the notice in each copy, and a minified bundle drops it. The fonts are
// left out because public/fonts-OFL.txt already carries their licence.
// licenses/*.txt adds what no package ships a file for: the icon sets
// react-icons copies its glyphs from.
const EXTRA_LICENSES = new URL('./licenses/', import.meta.url)

function thirdPartyLicenses() {
  return {
    name: 'third-party-licenses',
    generateBundle(_, bundle) {
      const packages = new Map()
      for (const file of Object.values(bundle)) {
        if (file.type !== 'chunk') continue
        for (const id of file.moduleIds) {
          const m = id.match(/^(.*\/node_modules\/((?:@[^/]+\/)?[^/]+))\//)
          if (m && !m[2].startsWith('@fontsource')) packages.set(m[1], m[2])
        }
      }
      const entries = [...packages]
        .sort(([, a], [, b]) => a.localeCompare(b))
        .map(([dir, name]) => {
          const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
          const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f))
          const text = file ? readFileSync(join(dir, file), 'utf8').trim() : `License: ${pkg.license}`
          return `${name} ${pkg.version}\n\n${text}\n`
        })
      for (const f of readdirSync(EXTRA_LICENSES).filter((f) => f.endsWith('.txt')).sort()) {
        entries.push(`${readFileSync(new URL(f, EXTRA_LICENSES), 'utf8').trim()}\n`)
      }
      const header =
        'Third-party software in the Zedstead web UI bundle, with each licence.\n' +
        'Generated by the build (webui/vite.config.js). The fonts are in fonts-OFL.txt.\n'
      this.emitFile({
        type: 'asset',
        fileName: 'third-party-licenses.txt',
        source: [header, ...entries].join(`\n${'='.repeat(72)}\n\n`),
      })
    },
  }
}

// Backend port for the dev proxy. scripts/dev.sh exports ZSM_API_PORT so a
// non-default `zsm web --port` still gets proxied; 8433 is the default.
const apiPort = process.env.ZSM_API_PORT || '8433'

// https://vite.dev/config/
export default defineConfig({
  plugins: [react(), thirdPartyLicenses()],
  server: {
    proxy: {
      // Same-origin from the browser's point of view, so the session cookie
      // and the /ws upgrade work exactly as they do against :8433. Object
      // form on purpose: Vite's string shorthand sets changeOrigin, which
      // rewrites Host to 127.0.0.1:<apiPort>, and the backend then refuses
      // every write as cross-origin (app/web/same_origin.py).
      '/api': {
        target: `http://127.0.0.1:${apiPort}`,
        changeOrigin: false,
      },
      '/ws': {
        target: `ws://127.0.0.1:${apiPort}`,
        ws: true,
      },
    },
  },
  build: {
    // Committed to git so `uv tool install` from git works without node —
    // see app/web/CLAUDE.md, "Web app". Must never be named "dist": root .gitignore
    // has a bare `dist/` entry that would swallow it at any depth.
    outDir: '../app/web/static',
    emptyOutDir: true,
  },
})
